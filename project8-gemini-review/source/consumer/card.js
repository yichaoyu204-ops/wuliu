(function (root) {
  'use strict';
  const W = 1080, inset = 84;
  const serif = '"DM Serif Text","Songti SC","Noto Serif CJK SC","SimSun",Georgia,serif';
  const sans = '"DM Sans","PingFang SC","Microsoft YaHei",Arial,sans-serif';
  function draw(canvas, model) {
    const ctx = canvas.getContext('2d');
    const cargo = model.style === 'cargo';
    const dark = cargo ? '#203d32' : '#432c3b';
    const accent = cargo ? '#a7492f' : '#804f70';
    const bodyFont = '50px ' + sans;
    const titleFont = '600 86px ' + serif;
    ctx.font = titleFont;
    const titleLines = NoteCore.wrap(ctx, model.title, W - inset * 2);
    ctx.font = bodyFont;
    const textLines = NoteCore.wrap(ctx, model.body, W - inset * 2);
    const bodyY = 248 + titleLines.length * 108 + 68;
    const footerY = Math.max(1188, bodyY + textLines.length * 76 + 105);
    canvas.width = W;
    canvas.height = footerY + 132;
    ctx.fillStyle = cargo ? '#fbf5e8' : '#faf0eb';
    ctx.fillRect(0, 0, W, canvas.height);
    ctx.fillStyle = dark;
    ctx.fillRect(0, 0, W, 32);
    ctx.fillStyle = accent;
    ctx.fillRect(inset, 117, 19, 19);
    ctx.font = '600 27px ' + sans;
    ctx.fillStyle = dark;
    ctx.fillText(cargo ? 'DISPATCH NOTES' : 'PERSONAL NOTES', inset + 35, 139);
    const edition = model.synthetic ? (model.lang === 'zh' ? '虚构示例' : 'Fictional sample') : (model.lang === 'zh' ? '寄语' : 'Dispatch Notes');
    ctx.textAlign = 'right';
    ctx.font = '33px ' + sans;
    ctx.fillText(edition, W - inset, 139);
    ctx.textAlign = 'left';
    ctx.fillRect(inset, 176, W - inset * 2, 2);
    ctx.font = titleFont;
    titleLines.forEach((line,i) => ctx.fillText(line,inset,290+i*108));
    ctx.fillStyle = accent;
    ctx.fillRect(inset,bodyY-84,70,7);
    ctx.fillStyle = dark;
    ctx.font = bodyFont;
    textLines.forEach((line,i) => ctx.fillText(line,inset,bodyY+i*76));
    ctx.fillStyle = dark;
    ctx.fillRect(inset,footerY,W-inset*2,2);
    ctx.font = 'italic 32px Georgia,serif';
    ctx.fillText('Dispatch Notes',inset,footerY+65);
    ctx.font = '28px ' + serif;
    ctx.textAlign = 'right';
    ctx.fillText('寄语',W-inset,footerY+65);
    ctx.textAlign = 'left';
    return {width:W,height:canvas.height,lines:textLines.length};
  }
  root.drawNote = draw;
})(globalThis);
